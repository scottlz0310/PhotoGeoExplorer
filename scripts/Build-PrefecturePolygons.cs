#:package NetTopologySuite@2.6.0
#:package NetTopologySuite.IO.Esri.Shapefile@1.2.0

// 同梱データ PhotoGeoExplorer.Core/Resources/prefecture-polygons.tsv を作り直すスクリプト。
//
// 入力: e-Stat「国勢調査 小地域（町丁・字等別）境界データ」（Shapefile、世界測地系緯度経度）の ZIP を
//       都道府県ごとに 1 つずつ置いたフォルダー（r2ka01.zip 〜 r2ka47.zip）。
// 出力: 都道府県ごとに、小地域のポリゴンを融合して外側へ膨らませ、簡略化したポリゴン。
//       元の範囲を必ず覆う（県境付近の地点は、隣接する都道府県の両方に入る）。
//
// 実行: dotnet run scripts/Build-PrefecturePolygons.cs -- <ZIP のフォルダー> <出力ファイル>
// 手順と出典は PhotoGeoExplorer.Core/Resources/README.md を参照。

using System.Globalization;
using System.IO.Compression;
using System.Text;
using NetTopologySuite.Geometries;
using NetTopologySuite.Geometries.Prepared;
using NetTopologySuite.IO;
using NetTopologySuite.IO.Esri;
using NetTopologySuite.IO.Esri.Shapefiles.Readers;
using NetTopologySuite.Operation.Union;
using NetTopologySuite.Simplify;

// 単位は度。膨らませる幅は、2 回の簡略化のずれの合計より大きくして、元の範囲を覆うことを保証する
const double PreSimplifyTolerance = 0.0002;
const double BufferDistance = 0.01;
const double SimplifyTolerance = 0.004;
// WKTWriter は、この桁数 + 1 桁（小数 5 桁、約 1m）まで書き出す
const int CoordinateDecimals = 4;

if (args.Length != 2)
{
    Console.Error.WriteLine("usage: dotnet run scripts/Build-PrefecturePolygons.cs -- <zip directory> <output file>");
    return 2;
}

Encoding.RegisterProvider(CodePagesEncodingProvider.Instance);
var zipDirectory = args[0];
var outputPath = args[1];
var lines = new List<string>
{
    "# code\tWKT (longitude latitude, JGD2011). Generated by scripts/Build-PrefecturePolygons.cs. Do not edit by hand."
};
var results = new string[47];
var totalVertices = 0;

// 都道府県ごとに独立なので並列に処理する（全体で 6〜7 分。北海道が最も長い）
Parallel.For(1, 48, prefecture =>
{
    var writer = new WKTWriter { PrecisionModel = new PrecisionModel(Math.Pow(10, CoordinateDecimals)) };
    var code = prefecture.ToString("00", CultureInfo.InvariantCulture);
    var zipPath = Path.Combine(zipDirectory, $"r2ka{code}.zip");
    var workDirectory = Path.Combine(Path.GetTempPath(), "prefecture-polygons-" + Guid.NewGuid().ToString("N"));
    Directory.CreateDirectory(workDirectory);
    try
    {
        ZipFile.ExtractToDirectory(zipPath, workDirectory);
        var shapefilePath = Directory.GetFiles(workDirectory, "*.shp").Single();
        var projection = File.ReadAllText(Path.ChangeExtension(shapefilePath, ".prj")).TrimStart();
        if (!projection.StartsWith("GEOGCS", StringComparison.OrdinalIgnoreCase))
        {
            throw new InvalidDataException($"{zipPath} is not in a geographic coordinate system.");
        }

        // 実データには不正な図形が含まれる（厳格に読むと失敗する県がある）ので、修復して読む
        var options = new ShapefileReaderOptions { GeometryBuilderMode = GeometryBuilderMode.FixInvalidShapes };
        var regions = Shapefile.ReadAllGeometries(shapefilePath, options)
            .Where(geometry => geometry is Polygon or MultiPolygon && !geometry.IsEmpty)
            .ToList();

        // 融合の前に小地域ごとに簡略化して、処理時間を抑える。
        // 小さな島などは簡略化で図形が潰れて消えるので、その場合は元の図形を使う
        var union = CascadedPolygonUnion.Union(regions.Select(PreSimplify).ToList());
        var simplified = DouglasPeuckerSimplifier.Simplify(
            union.Buffer(BufferDistance, quadrantSegments: 2),
            SimplifyTolerance);
        simplified = RemoveHoles(simplified.IsValid ? simplified : simplified.Buffer(0));

        // 簡略化で一部が欠けた小地域（複数の図形からなり、小さな島だけが潰れたものなど）は、
        // 元の図形を膨らませて足す
        var prepared = PreparedGeometryFactory.Prepare(simplified);
        var uncovered = regions.Where(region => !prepared.Covers(region)).ToList();
        if (uncovered.Count > 0)
        {
            var patch = CascadedPolygonUnion.Union(uncovered).Buffer(BufferDistance, quadrantSegments: 2);
            simplified = RemoveHoles(simplified.Union(patch));
            prepared = PreparedGeometryFactory.Prepare(simplified);
        }

        // 元の小地域がすべて覆われていることを確かめる
        var stillUncovered = regions.Count(region => !prepared.Covers(region));
        if (stillUncovered > 0)
        {
            throw new InvalidDataException($"{code}: {stillUncovered} of {regions.Count} regions are not covered by the simplified polygon.");
        }

        results[prefecture - 1] = $"{code}\t{writer.Write(simplified)}";
        Interlocked.Add(ref totalVertices, simplified.NumPoints);
        Console.WriteLine($"{code}: regions={regions.Count} vertices={simplified.NumPoints} parts={simplified.NumGeometries} patched={uncovered.Count}");
    }
    finally
    {
        Directory.Delete(workDirectory, recursive: true);
    }
});

lines.AddRange(results);

// 改行は LF、文字コードは BOM なしの UTF-8（中身は ASCII だけ）に固定して、作り直しても差分が出ないようにする
File.WriteAllText(outputPath, string.Join('\n', lines) + "\n", new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
Console.WriteLine($"total vertices={totalVertices} size={new FileInfo(outputPath).Length} bytes -> {outputPath}");
return 0;

static Geometry PreSimplify(Geometry region)
{
    var simplified = DouglasPeuckerSimplifier.Simplify(region, PreSimplifyTolerance);
    if (!simplified.IsValid)
    {
        simplified = simplified.Buffer(0);
    }

    return simplified.IsEmpty ? region : simplified;
}

// 穴は、都道府県の内側にあるので「覆う」保証に影響しない。データを小さくするために取り除く
static Geometry RemoveHoles(Geometry geometry)
{
    var factory = geometry.Factory;
    var polygons = new List<Polygon>();
    for (var i = 0; i < geometry.NumGeometries; i++)
    {
        if (geometry.GetGeometryN(i) is Polygon polygon)
        {
            polygons.Add(factory.CreatePolygon(factory.CreateLinearRing(polygon.ExteriorRing.Coordinates)));
        }
    }

    return polygons.Count == 1 ? polygons[0] : CascadedPolygonUnion.Union(polygons.Cast<Geometry>().ToList());
}
